function loadState() {
  try {
    const raw = window.localStorage.getItem(STATE_KEY);
    if (raw) return JSON.parse(raw);
  } catch {
    // fall through to a fresh state
  }
  const fresh = buildInitialState();
  saveState(fresh);
  return fresh;
}

function saveState(state) {
  try {
    window.localStorage.setItem(STATE_KEY, JSON.stringify(state));
  } catch {
    // storage full or blocked: the demo keeps working for this page load only
  }
}

/** Turns demo mode on with fresh sample data. */
export function startDemo() {
  window.localStorage.setItem(STATE_KEY, JSON.stringify(buildInitialState()));
  window.localStorage.setItem(FLAG_KEY, '1');
}

export function stopDemo() {
  try {
    window.localStorage.removeItem(FLAG_KEY);
    window.localStorage.removeItem(STATE_KEY);
    window.sessionStorage.removeItem('demoBannerDismissed');
  } catch {
    // ignore
  }
}

const json = (body, status = 200) =>
  new Response(JSON.stringify(body), { status, headers: { 'Content-Type': 'application/json' } });

function sampleRecommendations(prompt) {
  const crop = (/for an? (.+?) field/i.exec(prompt || '') || [])[1] || 'your crop';
  return (
    STATIC_NOTE +
    `<b>${crop}</b><br/>` +
    '• <b>Watering:</b> water deeply but rarely; check soil moisture 10 cm down before irrigating.<br/>' +
    '• <b>Fertilizing:</b> base fertilizer before sowing, then split nitrogen across the growing season.<br/>' +
    '• <b>Pests:</b> scout the field weekly and treat only when thresholds are reached.<br/>' +
    '• <b>Harvest:</b> follow crop-specific moisture and maturity signs rather than the calendar.<br/>' +
    '• <b>Soil:</b> rotate crops and keep residues to protect organic matter.<br/><br/>' +
    '<i>The live AI uses a free Google Gemini key that has probably expired, so this demo shows static example text.</i>'
  );
}

function withAuthor(state, message) {
  const people = [state.me, ...state.neighbours];
  const author = people.find((p) => p._id === message.authorId) || people.find((p) => p.email === message.authorEmail);
  return {
    ...message,
    authorDetails: author
      ? { username: author.username, email: author.email, profileImageUrl: author.profileImageUrl }
      : { username: message.authorEmail, email: message.authorEmail },
  };
}

async function readJson(init) {
  try {
    return JSON.parse((init && init.body) || '{}');
  } catch {
    return {};
  }
}

async function route(url, init) {
  const method = ((init && init.method) || 'GET').toUpperCase();
  const u = new URL(url, window.location.origin);
  const path = u.pathname;
  const state = loadState();

  switch (path) {
    case '/api/auth/checkAuth':
      return json({ message: 'Authenticated', email: state.me.email, crops: state.crops, isDemo: true });
    case '/api/auth/getCrops':
      return json({ crops: state.crops });
    case '/api/auth/saveCrops': {
      const body = await readJson(init);
      state.crops = body.crops || {};
      saveState(state);
      return json({ message: 'Crops saved' });
    }
    case '/api/auth/logout':
      stopDemo();
      return json({ message: 'Logged out' });

    case '/api/profile/userProfile':
      return json({
        email: state.me.email,
        username: state.me.username,
        createdAt: state.me.createdAt,
        profileImageUrl: state.me.profileImageUrl,
        crops: state.crops,
        friends: state.friends,
        friendRequests: state.friendRequests,
      });
    case '/api/profile/updateProfile': {
      const body = await readJson(init);
      if (body.username) state.me.username = String(body.username).slice(0, 30);
      saveState(state);
      return json({ message: 'Profile updated' });
    }
    case '/api/profile/uploadImage':
      return json({ error: 'Image uploads are disabled in the demo.' }, 503);
    case '/api/profile/getFriends':
      return json({ friends: state.friends });
    case '/api/profile/sendRequest':
      return json({ message: 'Friend request sent (demo: nobody will receive it).' });
    case '/api/profile/acceptRequest': {
      const body = await readJson(init);
      const req = state.friendRequests.find((r) => r.fromEmail === body.fromEmail);
      state.friendRequests = state.friendRequests.filter((r) => r.fromEmail !== body.fromEmail);
      if (req && body.accepted) {
        state.friends.push({
          _id: req.fromUserId,
          email: req.fromEmail,
          username: req.fromUsername,
          profileImageUrl: null,
        });
      }
      saveState(state);
      return json({ message: body.accepted ? 'Friend request accepted' : 'Friend request declined' });
    }

    case '/api/messages/getMessages': {
      const sorted = [...state.messages].sort((a, b) => new Date(a.timestamp) - new Date(b.timestamp));
      return json({ messages: sorted.map((m) => withAuthor(state, m)) });
    }
    case '/api/messages/postMessage': {
      const form = init && init.body;
      const content = form && typeof form.get === 'function' ? String(form.get('content') || '') : '';
      const message = {
        _id: `m-${rid()}`,
        content,
        authorId: state.me._id,
        authorEmail: state.me.email,
        timestamp: new Date().toISOString(),
        imageUrl: null,
        reactions: {},
        reactedUsers: {},
        replies: [],
      };
      state.messages.push(message);
      saveState(state);
      return json({ message: withAuthor(state, message) }, 201);
    }
    case '/api/messages/react': {
      const { messageId, reaction, action, userEmail } = await readJson(init);
      const message = state.messages.find((m) => m._id === messageId);
      if (!message) return json({ error: 'Message not found' }, 404);
      message.reactions = message.reactions || {};
      message.reactedUsers = message.reactedUsers || {};
      const users = message.reactedUsers[reaction] || [];
      if (action === 'like' && !users.includes(userEmail)) {
        message.reactedUsers[reaction] = [...users, userEmail];
        message.reactions[reaction] = (message.reactions[reaction] || 0) + 1;
      } else if (action === 'unlike' && users.includes(userEmail)) {
        message.reactedUsers[reaction] = users.filter((e) => e !== userEmail);
        message.reactions[reaction] = Math.max(0, (message.reactions[reaction] || 0) - 1);
      }
      saveState(state);
      return json({ reactions: message.reactions, reactedUsers: message.reactedUsers });
    }
    case '/api/messages/postReply': {
      const { messageId, content, userEmail } = await readJson(init);
      const message = state.messages.find((m) => m._id === messageId);
      if (!message) return json({ error: 'Invalid messageId' }, 400);
      const reply = { messageId, content, authorEmail: userEmail || state.me.email, timestamp: new Date().toISOString() };
      message.replies = [...(message.replies || []), reply];
      saveState(state);
      return json({ reply }, 201);
    }

    case '/api/community/tips': {
      const crop = (u.searchParams.get('crop') || '').toLowerCase();
      const tips = state.tips
        .filter((t) => t.crop === crop)
        .sort((a, b) => new Date(b.createdAt) - new Date(a.createdAt))
        .slice(0, 20);
      return json({ tips });
    }
    case '/api/community/shareTip': {
      const { crop, tip } = await readJson(init);
      if (!crop || !tip) return json({ error: 'Missing required fields' }, 400);
      const doc = {
        _id: `t-${rid()}`,
        crop: String(crop).toLowerCase(),
        content: tip,
        author: state.me.username,
        authorId: state.me._id,
        createdAt: new Date().toISOString(),
        rating: 0,
        votes: 0,
      };
      state.tips.push(doc);
      saveState(state);
      return json({ success: true, tip: doc });
    }

    case '/api/ai/actions': {
      const body = await readJson(init);
      return json({ reply: sampleRecommendations(body.message) });
    }

    default:
      return null;
  }
}

let installed = false;

/** Wraps window.fetch so /api/* calls are answered locally while demo mode is on. Safe to call repeatedly. */
export function installDemoFetch() {
  if (installed || typeof window === 'undefined') return;
  installed = true;
  const realFetch = window.fetch.bind(window);

  window.fetch = async (input, init) => {
    if (isDemoMode()) {
      const url = typeof input === 'string' ? input : input instanceof URL ? input.href : input.url;
      if (/^(https?:\/\/[^/]+)?\/api\//.test(url)) {
        try {
          const response = await route(url, init);
          if (response) return response;
        } catch (error) {
          console.error('Demo backend error:', error);
          return json({ error: 'Demo backend error' }, 500);
        }
      }
    }
    return realFetch(input, init);
  };
}
