/**
 * Demo mode that needs no server, database or account.
 *
 * "Try application" on the sign-in page calls startDemo(), which stores sample data in the visitor's own
 * browser (localStorage). While demo mode is on, requests to /api/* are answered from that local data by a
 * small fetch wrapper (installDemoFetch), so every page works unchanged. Nothing is sent to or saved on
 * the server, and clearing the browser data or logging out removes the demo.
 */

const FLAG_KEY = 'ffDemo';
const STATE_KEY = 'ffDemoState';

export const DEMO_EMAIL = 'demo@farmflow.app';

const rid = () => Math.random().toString(36).slice(2, 10) + Date.now().toString(36).slice(-4);
const ago = (ms) => new Date(Date.now() - ms).toISOString();
const dayIso = (days) => new Date(Date.now() - days * 86400000).toISOString().split('T')[0];

export function isDemoMode() {
  try {
    return typeof window !== 'undefined' && window.localStorage.getItem(FLAG_KEY) === '1';
  } catch {
    return false;
  }
}

function field(lon, lat, dLon, dLat, id) {
  return {
    type: 'Feature',
    properties: { id },
    geometry: {
      type: 'Polygon',
      coordinates: [[[lon, lat], [lon + dLon, lat], [lon + dLon, lat + dLat], [lon, lat + dLat], [lon, lat]]],
    },
  };
}

